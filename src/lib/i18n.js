const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function toLocaleDigits(value, lang) {
  const str = String(value);
  return lang === "bn" ? str.replace(/\d/g, (d) => BN_DIGITS[d]) : str;
}

export function useI18n() {
  const { lang } = useStore();
  const t = (key) => dict[lang][key] ?? dict.en[key] ?? key;
  const num = (value) => toLocaleDigits(value, lang);
  const price = (value) => "৳" + toLocaleDigits(Number(value).toLocaleString("en-IN"), lang);
  // pick the right language from a { en, bn } object
  const pick = (obj) => (obj ? (obj[lang] ?? obj.en) : "");
  return { lang, t, num, price, pick };
}
